def update_hospitals():
    print(f"🚀 开始同步 {len(hospital_data)} 条医院数据...")
    
    with engine.begin() as conn:
        for region, name, code in hospital_data:
            # 使用 PostgreSQL 的 ON CONFLICT 语法：如果 code 冲突，则不执行插入（DO NOTHING）
            sql = text("""
                INSERT INTO hospitals (region, name, code) 
                VALUES (:region, :name, :code)
                ON CONFLICT (code) DO NOTHING;
            """)
            conn.execute(sql, {"region": region, "name": name, "code": code})
            
    print("✅ 医院数据同步完成！")

